SET search_path TO general, public;

CREATE TABLE IF NOT EXISTS autogestionaprobador (
    id            integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_autogestionaprobador PRIMARY KEY,
    clienteid     integer       NULL,
    correo        varchar(200)  NOT NULL,
    nombre        varchar(150)  NULL,
    activo        boolean       NOT NULL DEFAULT true,
    usuario       varchar(150)  NULL,
    fecha         timestamp(3)  NOT NULL DEFAULT LOCALTIMESTAMP,
    fechamodifica timestamp(3)  NULL
);
CREATE INDEX IF NOT EXISTS ix_autogestionaprobador_cliente ON autogestionaprobador (clienteid, activo);

