-- 2) Funciones de seccion -------------------------------------------------
CREATE OR REPLACE FUNCTION fn_autogestionseccion(p_estadoid integer)
RETURNS varchar LANGUAGE sql STABLE AS $$
    SELECT s.nombre::varchar
    FROM general.estado e
    JOIN general.modulo m ON m.id = e.moduloid
    JOIN general.seccion s ON s.id = m.seccionid
    WHERE e.id = p_estadoid
    LIMIT 1
$$;

CREATE OR REPLACE FUNCTION fn_autogestionesproduccion(p_estadoid integer)
RETURNS integer LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN COALESCE(fn_autogestionseccion(p_estadoid), '') ILIKE 'Prod%' THEN 1 ELSE 0 END
$$;

-- Serial con estado final SCRAP en Reparacion (Maestro.codigo/descripcion empieza por SCRAP)
CREATE OR REPLACE FUNCTION fn_autogestionesscrap(p_serialid integer)
RETURNS integer LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN EXISTS (
        SELECT 1
        FROM reparacion r
        JOIN maestro m ON m.id = r.estadofinalid
        WHERE r.serialid = p_serialid
          AND (m.codigo ILIKE 'SCRAP%' OR m.descripcion ILIKE 'SCRAP%')
    ) THEN 1 ELSE 0 END
$$;

-- Descripcion del Movimiento: "AUTOGESTION Envío a X, Desde: Y"
CREATE OR REPLACE FUNCTION fn_autogestiondescripcion(p_origenid integer, p_destinoid integer)
RETURNS varchar LANGUAGE sql STABLE AS $$
    SELECT ('AUTOGESTION Envío a '
         || COALESCE((SELECT e.nombre FROM general.estado e WHERE e.id = p_destinoid), '?')
         || ', Desde: '
         || COALESCE((SELECT e.nombre FROM general.estado e WHERE e.id = p_origenid), '?'))::varchar
$$;

