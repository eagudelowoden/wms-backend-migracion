-- 4) Buscar serial: donde esta ------------------------------------------------
DROP FUNCTION IF EXISTS pa_autogestionbuscarserial(varchar);
CREATE FUNCTION pa_autogestionbuscarserial(p_serial varchar)
RETURNS TABLE (id integer, serial varchar, mac varchar, codigo varchar, descripcion varchar,
               estadoid integer, estado varchar, palletid integer, pallet varchar,
               cajaempaqueid integer, cajaempaque varchar, modulo varchar, seccion varchar,
               esproduccion integer, esscrap integer, palletidempaque integer)
LANGUAGE sql STABLE AS $$
    SELECT i.id, i.serial::varchar, i.mac::varchar, cs.codigo::varchar, cs.descripcion::varchar,
           i.estadoid, es.nombre::varchar,
           i.palletid, p.numero::varchar,
           i.cajaempaqueid, ce.numero::varchar,
           m.nombre::varchar, s.nombre::varchar,
           fn_autogestionesproduccion(i.estadoid),
           fn_autogestionesscrap(i.id),
           COALESCE(i.palletidempaque, 0)
    FROM ingreso i
    LEFT JOIN codigosap cs ON cs.id = i.codigosapid
    LEFT JOIN general.estado es ON es.id = i.estadoid
    LEFT JOIN general.modulo m ON m.id = es.moduloid
    LEFT JOIN general.seccion s ON s.id = m.seccionid
    LEFT JOIN pallet p ON p.id = i.palletid
    LEFT JOIN cajaempaque ce ON ce.id = i.cajaempaqueid
    WHERE i.serial = p_serial
$$;

-- 5) Accion sobre un serial ----------------------------------------------------
--    ESTADO: mueve a un estado de Produccion; palletid = 0, cajaempaqueid = 0 y se borra de Empaque
--    CAJA  : "sacar": palletid = 0, cajaempaqueid = 0, estado = P-EMPAQUE y se borra de Empaque
--    PALLET: lo pasa a otro pallet (de Produccion); cajaempaqueid = 0 y se borra de Empaque
DROP FUNCTION IF EXISTS pa_autogestionserial(varchar, varchar, integer, varchar, integer, varchar);
DROP FUNCTION IF EXISTS pa_autogestionserial(varchar, varchar, integer, varchar, integer, varchar, integer);
CREATE FUNCTION pa_autogestionserial(
    p_serial varchar, p_accion varchar, p_usuarioid integer, p_justificacion varchar,
    p_estadodestinoid integer DEFAULT NULL, p_palletdestino varchar DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v_id integer; v_estadoorigen integer; v_palletorigen integer; v_cajaorigen integer;
    v_nuevoestado integer; v_nuevopallet integer; v_nuevacaja integer;
    v_estadosacado integer; v_palletdestinoid integer; v_palletdestinoestado integer; v_palletempaque integer;
BEGIN
    IF length(btrim(COALESCE(p_justificacion, ''))) < 10 THEN
        RAISE EXCEPTION 'La justificacion es obligatoria (minimo 10 caracteres).';
    END IF;

    SELECT i.id, i.estadoid, i.palletid, i.cajaempaqueid, i.palletidempaque
      INTO v_id, v_estadoorigen, v_palletorigen, v_cajaorigen, v_palletempaque
    FROM ingreso i WHERE i.serial = p_serial;

    IF v_id IS NULL THEN
        RAISE EXCEPTION 'El serial no existe.';
    END IF;

    -- mismo candado que el empaque: no mover el serial mientras se esta empacando
    PERFORM pg_advisory_xact_lock(hashtext('empaque:' || v_id::text));

    IF fn_autogestionesproduccion(v_estadoorigen) = 0 THEN
        RAISE EXCEPTION 'El serial esta en un modulo de Logistica (o fuera de Produccion): solo se puede consultar.';
    END IF;

    IF fn_autogestionesscrap(v_id) = 1 THEN
        RAISE EXCEPTION 'No se puede realizar el movimiento: el serial tiene estado final SCRAP en Reparacion.';
    END IF;

    -- Serial ya empacado en un pallet de empaque: solo se puede sacar de la caja (accion CAJA)
    IF COALESCE(v_palletempaque, 0) > 0 AND p_accion <> 'CAJA' THEN
        RAISE EXCEPTION 'No se puede mover: el serial esta empacado (tiene pallet de empaque).';
    END IF;

    v_nuevoestado := v_estadoorigen;
    v_nuevopallet := v_palletorigen;
    v_nuevacaja   := v_cajaorigen;

    -- Estado al que vuelve un serial "sacado" de su caja (mismo que usa Empaque al quitar un serial)
    SELECT e.id INTO v_estadosacado FROM general.estado e WHERE UPPER(e.nombre) = 'P-EMPAQUE' LIMIT 1;

    IF p_accion = 'ESTADO' THEN
        IF p_estadodestinoid IS NULL
           OR NOT EXISTS (SELECT 1 FROM autogestionestadodestino d WHERE d.ambito = 'SERIAL' AND d.estadoid = p_estadodestinoid) THEN
            RAISE EXCEPTION 'El estado destino no esta permitido para seriales.';
        END IF;
        v_nuevoestado := p_estadodestinoid;
        v_nuevopallet := 0;
        v_nuevacaja   := 0;
    ELSIF p_accion = 'CAJA' THEN
        IF COALESCE(v_cajaorigen, 0) = 0 THEN
            RAISE EXCEPTION 'El serial no esta en una caja.';
        END IF;
        IF v_estadosacado IS NULL THEN
            RAISE EXCEPTION 'No se encontro el estado P-EMPAQUE para dejar el serial.';
        END IF;
        v_nuevoestado := v_estadosacado;
        v_nuevopallet := 0;
        v_nuevacaja   := 0;
    ELSIF p_accion = 'PALLET' THEN
        SELECT p.id, p.destinoid INTO v_palletdestinoid, v_palletdestinoestado FROM pallet p WHERE p.numero = p_palletdestino;
        IF v_palletdestinoid IS NULL THEN
            RAISE EXCEPTION 'El pallet destino no existe.';
        END IF;
        IF fn_autogestionesproduccion(v_palletdestinoestado) = 0 THEN
            RAISE EXCEPTION 'El pallet destino esta en Logistica (o fuera de Produccion).';
        END IF;
        v_nuevopallet := v_palletdestinoid;
        v_nuevacaja   := 0;
    ELSE
        RAISE EXCEPTION 'Accion no valida.';
    END IF;

    UPDATE ingreso
    SET estadoid = v_nuevoestado,
        palletid = v_nuevopallet,
        cajaempaqueid = v_nuevacaja,
        usuarioidmovimiento = p_usuarioid,
        fechamovimiento = LOCALTIMESTAMP
    WHERE id = v_id;

    -- El serial ya no esta en ninguna caja: se elimina de la tabla Empaque (por serialid)
    IF v_nuevacaja = 0 THEN
        DELETE FROM empaque WHERE serialid = v_id;
    END IF;

    IF COALESCE(v_nuevoestado, 0) <> COALESCE(v_estadoorigen, 0) THEN
        INSERT INTO movimiento (serialid, serial, origenid, destinoid, descripcion, usuarioid, fecha)
        VALUES (v_id, p_serial, v_estadoorigen, v_nuevoestado, fn_autogestiondescripcion(v_estadoorigen, v_nuevoestado), p_usuarioid, LOCALTIMESTAMP);
    END IF;

    INSERT INTO autogestionlog (usuarioid, accion, serialid, serial, estadoorigenid, estadodestinoid,
                                palletorigenid, palletdestinoid, cajaorigenid, cajadestinoid, cantidad, justificacion)
    VALUES (p_usuarioid, p_accion, v_id, p_serial, v_estadoorigen, v_nuevoestado,
            NULLIF(v_palletorigen, 0), NULLIF(v_nuevopallet, 0), NULLIF(v_cajaorigen, 0), NULLIF(v_nuevacaja, 0),
            1, btrim(p_justificacion));
END;
$$;

-- 6) Buscar pallet: donde esta ---------------------------------------------------
DROP FUNCTION IF EXISTS pa_autogestionbuscarpallet(varchar);
CREATE FUNCTION pa_autogestionbuscarpallet(p_pallet varchar)
RETURNS TABLE (id integer, numero varchar, codigo varchar, descripcion varchar,
               destinoid integer, estado varchar, modulo varchar, seccion varchar,
               esproduccion integer, totalseriales integer, totalcajas integer,
               serialesscrap integer, serialesempacados integer)
LANGUAGE sql STABLE AS $$
    SELECT p.id, p.numero::varchar, cs.codigo::varchar, cs.descripcion::varchar,
           p.destinoid, es.nombre::varchar,
           m.nombre::varchar, s.nombre::varchar,
           fn_autogestionesproduccion(p.destinoid),
           (SELECT COUNT(*)::integer FROM ingreso i WHERE i.palletid = p.id),
           (SELECT COUNT(*)::integer FROM cajaempaque ce WHERE ce.palletid = p.id AND ce.activo = true),
           (SELECT COUNT(*)::integer FROM ingreso i WHERE i.palletid = p.id AND fn_autogestionesscrap(i.id) = 1),
           (SELECT COUNT(*)::integer FROM ingreso i WHERE i.palletid = p.id AND COALESCE(i.palletidempaque, 0) > 0)
    FROM pallet p
    LEFT JOIN codigosap cs ON cs.id = p.codigosapid
    LEFT JOIN general.estado es ON es.id = p.destinoid
    LEFT JOIN general.modulo m ON m.id = es.moduloid
    LEFT JOIN general.seccion s ON s.id = m.seccionid
    WHERE p.numero = p_pallet
$$;

-- 7) Cajas del pallet -------------------------------------------------------------
DROP FUNCTION IF EXISTS pa_autogestionpalletcajas(integer);
CREATE FUNCTION pa_autogestionpalletcajas(p_palletid integer)
RETURNS TABLE (id integer, numero varchar, cantidad integer) LANGUAGE sql STABLE AS $$
    SELECT ce.id, ce.numero::varchar, (SELECT COUNT(*)::integer FROM ingreso i WHERE i.cajaempaqueid = ce.id)
    FROM cajaempaque ce
    WHERE ce.palletid = p_palletid AND ce.activo = true
    ORDER BY ce.numero
$$;

-- 8) Accion sobre un pallet / sus cajas ---------------------------------------------
--    MOVER        : el pallet y TODOS sus seriales (y cajas) pasan a un estado de Produccion
--    CAJA_VACIAR  : saca los seriales de la caja: palletid = 0, cajaempaqueid = 0, estado P-EMPAQUE y se borran de Empaque
--    CAJA_ELIMINAR: igual que CAJA_VACIAR y ademas desactiva la caja
--    CAJA_PALLET  : pasa los seriales de la caja a otro pallet de Produccion (sin caja, fuera de Empaque)
DROP FUNCTION IF EXISTS pa_autogestionpallet(varchar, varchar, integer, varchar, integer, varchar, varchar);
CREATE FUNCTION pa_autogestionpallet(
    p_pallet varchar, p_accion varchar, p_usuarioid integer, p_justificacion varchar,
    p_estadodestinoid integer DEFAULT NULL, p_cajanumero varchar DEFAULT NULL, p_palletdestino varchar DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    v_palletid integer; v_estadoactual integer; v_cantidad integer := 0; v_cajaid integer;
    v_palletdestinoid integer; v_nuevoestado integer; v_estadosacado integer; v_estadopalletdestino integer;
    v_seriales integer[];
BEGIN
    IF length(btrim(COALESCE(p_justificacion, ''))) < 10 THEN
        RAISE EXCEPTION 'La justificacion es obligatoria (minimo 10 caracteres).';
    END IF;

    SELECT p.id, p.destinoid INTO v_palletid, v_estadoactual FROM pallet p WHERE p.numero = p_pallet;

    IF v_palletid IS NULL THEN
        RAISE EXCEPTION 'El pallet no existe.';
    END IF;

    IF fn_autogestionesproduccion(v_estadoactual) = 0 THEN
        RAISE EXCEPTION 'El pallet esta en un modulo de Logistica (o fuera de Produccion): solo se puede consultar.';
    END IF;

    -- Pallet con algun serial en SCRAP (Reparacion): ningun movimiento
    IF EXISTS (SELECT 1 FROM ingreso i WHERE i.palletid = v_palletid AND fn_autogestionesscrap(i.id) = 1) THEN
        RAISE EXCEPTION 'No se puede realizar el movimiento: el pallet tiene seriales con estado final SCRAP en Reparacion.';
    END IF;

    -- Pallet en Empaque o con seriales empacados: ninguna accion (mover, sacar seriales, pasar a pallet, eliminar caja)
    IF EXISTS (SELECT 1 FROM general.estado e WHERE e.id = v_estadoactual AND e.nombre ILIKE '%EMPAQUE%')
       OR EXISTS (SELECT 1 FROM ingreso i WHERE i.palletid = v_palletid AND COALESCE(i.palletidempaque, 0) > 0) THEN
        RAISE EXCEPTION 'No se puede mover: el pallet esta en Empaque o tiene seriales empacados.';
    END IF;

    v_nuevoestado := v_estadoactual;
    SELECT e.id INTO v_estadosacado FROM general.estado e WHERE UPPER(e.nombre) = 'P-EMPAQUE' LIMIT 1;

    IF p_accion IN ('CAJA_VACIAR', 'CAJA_ELIMINAR') AND v_estadosacado IS NULL THEN
        RAISE EXCEPTION 'No se encontro el estado P-EMPAQUE para dejar los seriales.';
    END IF;

    IF p_accion = 'MOVER' THEN
        IF p_estadodestinoid IS NULL
           OR NOT EXISTS (SELECT 1 FROM autogestionestadodestino d WHERE d.ambito = 'PALLET' AND d.estadoid = p_estadodestinoid) THEN
            RAISE EXCEPTION 'El estado destino no esta permitido para pallets (solo P-* y *-ENTREGA).';
        END IF;
        v_nuevoestado := p_estadodestinoid;
    ELSIF p_accion IN ('CAJA_VACIAR', 'CAJA_ELIMINAR', 'CAJA_PALLET') THEN
        SELECT ce.id INTO v_cajaid FROM cajaempaque ce
        WHERE ce.palletid = v_palletid AND ce.numero = p_cajanumero AND ce.activo = true;
        IF v_cajaid IS NULL THEN
            RAISE EXCEPTION 'La caja no existe en este pallet.';
        END IF;

        IF p_accion = 'CAJA_PALLET' THEN
            SELECT p.id, p.destinoid INTO v_palletdestinoid, v_estadopalletdestino FROM pallet p WHERE p.numero = p_palletdestino;
            IF v_palletdestinoid IS NULL THEN
                RAISE EXCEPTION 'El pallet destino no existe.';
            END IF;
            IF v_palletdestinoid = v_palletid THEN
                RAISE EXCEPTION 'El pallet destino debe ser distinto al actual.';
            END IF;
            IF fn_autogestionesproduccion(v_estadopalletdestino) = 0 THEN
                RAISE EXCEPTION 'El pallet destino esta en Logistica (o fuera de Produccion).';
            END IF;
        END IF;
    ELSE
        RAISE EXCEPTION 'Accion no valida.';
    END IF;

    IF p_accion = 'MOVER' THEN
        INSERT INTO movimiento (serialid, serial, origenid, destinoid, descripcion, usuarioid, fecha)
        SELECT i.id, i.serial, i.estadoid, v_nuevoestado, fn_autogestiondescripcion(i.estadoid, v_nuevoestado), p_usuarioid, LOCALTIMESTAMP
        FROM ingreso i
        WHERE i.palletid = v_palletid AND COALESCE(i.estadoid, 0) <> v_nuevoestado;

        UPDATE ingreso
        SET estadoid = v_nuevoestado, usuarioidmovimiento = p_usuarioid, fechamovimiento = LOCALTIMESTAMP
        WHERE palletid = v_palletid;
        GET DIAGNOSTICS v_cantidad = ROW_COUNT;

        UPDATE pallet
        SET destinoid = v_nuevoestado, usuarioidmodifica = p_usuarioid, fechamodifica = LOCALTIMESTAMP
        WHERE id = v_palletid;
    ELSE
        -- Seriales de la caja (se toman antes de modificar Ingreso)
        v_seriales := ARRAY(SELECT i.id FROM ingreso i WHERE i.cajaempaqueid = v_cajaid);

        -- mismo candado que el empaque, por cada serial (en orden para evitar bloqueos cruzados)
        PERFORM pg_advisory_xact_lock(hashtext('empaque:' || s::text)) FROM unnest(v_seriales) AS s ORDER BY s;

        -- Se eliminan de la tabla Empaque (por serialid)
        DELETE FROM empaque WHERE serialid = ANY (v_seriales);

        IF p_accion IN ('CAJA_VACIAR', 'CAJA_ELIMINAR') THEN
            -- "Sacar": palletid = 0, cajaempaqueid = 0 y vuelven a P-EMPAQUE
            INSERT INTO movimiento (serialid, serial, origenid, destinoid, descripcion, usuarioid, fecha)
            SELECT i.id, i.serial, i.estadoid, v_estadosacado, fn_autogestiondescripcion(i.estadoid, v_estadosacado), p_usuarioid, LOCALTIMESTAMP
            FROM ingreso i
            WHERE i.id = ANY (v_seriales) AND COALESCE(i.estadoid, 0) <> v_estadosacado;

            UPDATE ingreso
            SET estadoid = v_estadosacado, palletid = 0, cajaempaqueid = 0,
                usuarioidmovimiento = p_usuarioid, fechamovimiento = LOCALTIMESTAMP
            WHERE id = ANY (v_seriales);
            GET DIAGNOSTICS v_cantidad = ROW_COUNT;
            v_nuevoestado := v_estadosacado;
        ELSE
            -- CAJA_PALLET: pasan al otro pallet sin caja
            UPDATE ingreso
            SET palletid = v_palletdestinoid, cajaempaqueid = 0,
                usuarioidmovimiento = p_usuarioid, fechamovimiento = LOCALTIMESTAMP
            WHERE id = ANY (v_seriales);
            GET DIAGNOSTICS v_cantidad = ROW_COUNT;
        END IF;

        IF p_accion = 'CAJA_ELIMINAR' THEN
            UPDATE cajaempaque SET activo = false WHERE id = v_cajaid;
        END IF;
    END IF;

    INSERT INTO autogestionlog (usuarioid, accion, estadoorigenid, estadodestinoid,
                                palletorigenid, palletdestinoid, cajaorigenid, cantidad, justificacion)
    VALUES (p_usuarioid, 'PALLET_' || p_accion, v_estadoactual, v_nuevoestado,
            v_palletid, COALESCE(v_palletdestinoid, v_palletid), v_cajaid, v_cantidad, btrim(p_justificacion));
END;
$$;

-- 9) Consulta de logs --------------------------------------------------------------------
DROP FUNCTION IF EXISTS pa_autogestionlogs(varchar, integer);
CREATE FUNCTION pa_autogestionlogs(p_serial varchar DEFAULT NULL, p_limite integer DEFAULT 200)
RETURNS TABLE (id integer, fecha timestamp, nombreusuario varchar, accion varchar, serial varchar,
               estadoorigen varchar, estadodestino varchar, palletorigen varchar, palletdestino varchar,
               cajaorigen varchar, justificacion varchar, cantidad integer)
LANGUAGE sql STABLE AS $$
    SELECT l.id, l.fecha::timestamp, u.nombreusuario::varchar, l.accion::varchar, l.serial::varchar,
           eo.nombre::varchar, ed.nombre::varchar,
           po.numero::varchar, pd.numero::varchar,
           co.numero::varchar, l.justificacion::varchar, l.cantidad
    FROM autogestionlog l
    LEFT JOIN general.usuario u ON u.id = l.usuarioid
    LEFT JOIN general.estado eo ON eo.id = l.estadoorigenid
    LEFT JOIN general.estado ed ON ed.id = l.estadodestinoid
    LEFT JOIN pallet po ON po.id = l.palletorigenid
    LEFT JOIN pallet pd ON pd.id = l.palletdestinoid
    LEFT JOIN cajaempaque co ON co.id = l.cajaorigenid
    WHERE p_serial IS NULL OR l.serial = p_serial OR po.numero = p_serial OR pd.numero = p_serial
    ORDER BY l.fecha DESC, l.id DESC
    LIMIT p_limite
$$;

-- 10) Crear solicitud (valida en seco: ejecuta la accion y la deshace) --------------------
DROP FUNCTION IF EXISTS pa_autogestionsolicitudcrear(varchar, varchar, varchar, integer, varchar, integer, varchar, varchar, integer);
CREATE FUNCTION pa_autogestionsolicitudcrear(
    p_ambito varchar, p_accion varchar, p_objetivo varchar, p_solicitanteid integer, p_justificacion varchar,
    p_estadodestinoid integer DEFAULT NULL, p_cajanumero varchar DEFAULT NULL, p_palletdestino varchar DEFAULT NULL,
    p_horas integer DEFAULT 48)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE v_id integer;
BEGIN
    IF p_ambito NOT IN ('SERIAL', 'PALLET') THEN
        RAISE EXCEPTION 'Ambito no valido.';
    END IF;

    IF length(btrim(COALESCE(p_justificacion, ''))) < 10 THEN
        RAISE EXCEPTION 'La justificacion es obligatoria (minimo 10 caracteres).';
    END IF;

    IF EXISTS (SELECT 1 FROM autogestionsolicitud s
               WHERE s.ambito = p_ambito AND s.objetivo = p_objetivo AND s.estado = 'PENDIENTE' AND s.venceen > LOCALTIMESTAMP) THEN
        RAISE EXCEPTION 'Ya existe una solicitud pendiente de aprobacion para este elemento.';
    END IF;

    -- Validacion en seco: se ejecuta la accion real dentro de un subbloque y se deshace con un error propio
    -- (SQLSTATE AG999), asi se aplican exactamente las mismas reglas. Cualquier otro error se propaga.
    BEGIN
        IF p_ambito = 'SERIAL' THEN
            PERFORM pa_autogestionserial(p_serial => p_objetivo, p_accion => p_accion, p_usuarioid => p_solicitanteid,
                                         p_justificacion => p_justificacion, p_estadodestinoid => p_estadodestinoid,
                                         p_palletdestino => p_palletdestino);
        ELSE
            PERFORM pa_autogestionpallet(p_pallet => p_objetivo, p_accion => p_accion, p_usuarioid => p_solicitanteid,
                                         p_justificacion => p_justificacion, p_estadodestinoid => p_estadodestinoid,
                                         p_cajanumero => p_cajanumero, p_palletdestino => p_palletdestino);
        END IF;
        RAISE EXCEPTION 'validacion en seco' USING ERRCODE = 'AG999';
    EXCEPTION WHEN SQLSTATE 'AG999' THEN
        NULL;
    END;

    INSERT INTO autogestionsolicitud (ambito, accion, objetivo, estadodestinoid, cajanumero, palletdestino,
                                      solicitanteid, justificacion, venceen)
    VALUES (p_ambito, p_accion, p_objetivo, p_estadodestinoid, p_cajanumero, p_palletdestino,
            p_solicitanteid, btrim(p_justificacion), LOCALTIMESTAMP + make_interval(hours => p_horas))
    RETURNING id INTO v_id;

    RETURN v_id;
END;
$$;

-- 11) Guardar el token (hash) de un aprobador ----------------------------------------------
DROP FUNCTION IF EXISTS pa_autogestionsolicitudtoken(integer, integer, varchar, varchar, varchar);
CREATE FUNCTION pa_autogestionsolicitudtoken(
    p_solicitudid integer, p_aprobadorid integer, p_nombre varchar, p_correo varchar, p_tokenhash varchar)
RETURNS void LANGUAGE sql AS $$
    INSERT INTO autogestionsolicitudtoken (solicitudid, aprobadorid, nombre, correo, tokenhash)
    VALUES (p_solicitudid, p_aprobadorid, p_nombre, p_correo, p_tokenhash)
$$;

-- 12) Detalle de una solicitud a partir del token (NO consume el token) --------------------------
DROP FUNCTION IF EXISTS pa_autogestionsolicitudportoken(varchar);
CREATE FUNCTION pa_autogestionsolicitudportoken(p_tokenhash varchar)
RETURNS TABLE (id integer, ambito varchar, accion varchar, objetivo varchar, estadodestino varchar,
               cajanumero varchar, palletdestino varchar, solicitante varchar, fecha timestamp,
               justificacion varchar, estado varchar, venceen timestamp, aprobador varchar, vigente integer)
LANGUAGE sql STABLE AS $$
    SELECT s.id, s.ambito::varchar, s.accion::varchar, s.objetivo::varchar, ed.nombre::varchar,
           s.cajanumero::varchar, s.palletdestino::varchar, u.nombreusuario::varchar, s.fecha::timestamp,
           s.justificacion::varchar,
           (CASE WHEN s.estado = 'PENDIENTE' AND s.venceen <= LOCALTIMESTAMP THEN 'VENCIDA' ELSE s.estado END)::varchar,
           s.venceen::timestamp, t.nombre::varchar,
           CASE WHEN s.estado = 'PENDIENTE' AND s.venceen > LOCALTIMESTAMP AND t.usado = false THEN 1 ELSE 0 END
    FROM autogestionsolicitudtoken t
    JOIN autogestionsolicitud s ON s.id = t.solicitudid
    LEFT JOIN general.estado ed ON ed.id = s.estadodestinoid
    LEFT JOIN general.usuario u ON u.id = s.solicitanteid
    WHERE t.tokenhash = p_tokenhash
$$;

-- 13) Resolver: autorizar / rechazar (un solo uso, atomico) ------------------------------------
DROP FUNCTION IF EXISTS pa_autogestionsolicitudresolver(varchar, varchar);
CREATE FUNCTION pa_autogestionsolicitudresolver(p_tokenhash varchar, p_decision varchar)
RETURNS TABLE (resultado varchar, mensaje varchar) LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_solid integer; v_ambito varchar; v_accion varchar; v_objetivo varchar; v_estadodestinoid integer;
    v_cajanumero varchar; v_palletdestino varchar; v_solicitanteid integer; v_justificacion varchar;
    v_aprobador varchar; v_rows integer; v_justfinal varchar; v_msg varchar;
BEGIN
    IF p_decision NOT IN ('APROBAR', 'RECHAZAR') THEN
        RETURN QUERY SELECT 'INVALIDA'::varchar, 'Decision no valida.'::varchar;
        RETURN;
    END IF;

    SELECT s.id, s.ambito, s.accion, s.objetivo, s.estadodestinoid, s.cajanumero, s.palletdestino,
           s.solicitanteid, s.justificacion, t.nombre
      INTO v_solid, v_ambito, v_accion, v_objetivo, v_estadodestinoid, v_cajanumero, v_palletdestino,
           v_solicitanteid, v_justificacion, v_aprobador
    FROM autogestionsolicitudtoken t
    JOIN autogestionsolicitud s ON s.id = t.solicitudid
    WHERE t.tokenhash = p_tokenhash AND t.usado = false;

    IF v_solid IS NULL THEN
        RETURN QUERY SELECT 'INVALIDA'::varchar, 'El enlace no es valido o ya fue utilizado.'::varchar;
        RETURN;
    END IF;

    BEGIN  -- subtransaccion: si algo falla se deshace y se atiende en el EXCEPTION
        -- Reclama la solicitud de forma atomica: solo una persona puede resolverla
        UPDATE autogestionsolicitud
        SET estado = CASE WHEN p_decision = 'APROBAR' THEN 'APROBADA' ELSE 'RECHAZADA' END,
            fecharesolucion = LOCALTIMESTAMP,
            resueltapor = v_aprobador
        WHERE id = v_solid AND estado = 'PENDIENTE' AND venceen > LOCALTIMESTAMP;
        GET DIAGNOSTICS v_rows = ROW_COUNT;

        IF v_rows = 0 THEN
            UPDATE autogestionsolicitud SET estado = 'VENCIDA'
            WHERE id = v_solid AND estado = 'PENDIENTE' AND venceen <= LOCALTIMESTAMP;
            UPDATE autogestionsolicitudtoken SET usado = true, fechauso = LOCALTIMESTAMP WHERE solicitudid = v_solid AND usado = false;
            RETURN QUERY SELECT 'INVALIDA'::varchar, 'La solicitud ya fue resuelta o esta vencida.'::varchar;
            RETURN;
        END IF;

        -- Quema TODOS los tokens de la solicitud (el enlace queda de un solo uso)
        UPDATE autogestionsolicitudtoken SET usado = true, fechauso = LOCALTIMESTAMP WHERE solicitudid = v_solid AND usado = false;

        IF p_decision = 'APROBAR' THEN
            v_justfinal := left(v_justificacion || ' | Solicitud #' || v_solid::text || ' aprobada por ' || COALESCE(v_aprobador, '?'), 500);

            IF v_ambito = 'SERIAL' THEN
                PERFORM pa_autogestionserial(p_serial => v_objetivo, p_accion => v_accion, p_usuarioid => v_solicitanteid,
                                             p_justificacion => v_justfinal, p_estadodestinoid => v_estadodestinoid,
                                             p_palletdestino => v_palletdestino);
            ELSE
                PERFORM pa_autogestionpallet(p_pallet => v_objetivo, p_accion => v_accion, p_usuarioid => v_solicitanteid,
                                             p_justificacion => v_justfinal, p_estadodestinoid => v_estadodestinoid,
                                             p_cajanumero => v_cajanumero, p_palletdestino => v_palletdestino);
            END IF;

            UPDATE autogestionsolicitud SET resultado = 'Movimiento ejecutado.' WHERE id = v_solid;
        ELSE
            UPDATE autogestionsolicitud SET resultado = 'Solicitud rechazada.' WHERE id = v_solid;
        END IF;

        IF p_decision = 'APROBAR' THEN
            RETURN QUERY SELECT 'APROBADA'::varchar, 'Movimiento autorizado y ejecutado correctamente.'::varchar;
        ELSE
            RETURN QUERY SELECT 'RECHAZADA'::varchar, 'Solicitud rechazada. No se realizo ningun movimiento.'::varchar;
        END IF;
    EXCEPTION WHEN OTHERS THEN
        GET STACKED DIAGNOSTICS v_msg = MESSAGE_TEXT;
        v_msg := left(v_msg, 500);

        -- El token queda consumido igual; la solicitud queda en ERROR con el motivo
        UPDATE autogestionsolicitud
        SET estado = 'ERROR', fecharesolucion = LOCALTIMESTAMP, resueltapor = v_aprobador, resultado = v_msg
        WHERE id = v_solid AND estado = 'PENDIENTE';
        UPDATE autogestionsolicitudtoken SET usado = true, fechauso = LOCALTIMESTAMP WHERE solicitudid = v_solid AND usado = false;

        RETURN QUERY SELECT 'ERROR'::varchar, v_msg;
    END;
END;
$$;

-- 14) Listado de solicitudes (pestana Solicitudes) -----------------------------------------------
DROP FUNCTION IF EXISTS pa_autogestionsolicitudes(integer);
CREATE FUNCTION pa_autogestionsolicitudes(p_limite integer DEFAULT 100)
RETURNS TABLE (id integer, fecha timestamp, ambito varchar, accion varchar, objetivo varchar, estadodestino varchar,
               solicitante varchar, estado varchar, venceen timestamp, resueltapor varchar,
               fecharesolucion timestamp, resultado varchar, justificacion varchar)
LANGUAGE sql STABLE AS $$
    SELECT s.id, s.fecha::timestamp, s.ambito::varchar, s.accion::varchar, s.objetivo::varchar, ed.nombre::varchar,
           u.nombreusuario::varchar,
           (CASE WHEN s.estado = 'PENDIENTE' AND s.venceen <= LOCALTIMESTAMP THEN 'VENCIDA' ELSE s.estado END)::varchar,
           s.venceen::timestamp, s.resueltapor::varchar, s.fecharesolucion::timestamp, s.resultado::varchar,
           s.justificacion::varchar
    FROM autogestionsolicitud s
    LEFT JOIN general.estado ed ON ed.id = s.estadodestinoid
    LEFT JOIN general.usuario u ON u.id = s.solicitanteid
    ORDER BY s.fecha DESC, s.id DESC
    LIMIT p_limite
$$;

-- 15) Cancelar una solicitud que no pudo completarse (la libera para reintentar) ---------------------
DROP FUNCTION IF EXISTS pa_autogestionsolicitudcancelar(integer, varchar);
CREATE FUNCTION pa_autogestionsolicitudcancelar(p_solicitudid integer, p_motivo varchar)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    UPDATE autogestionsolicitud
    SET estado = 'ERROR', fecharesolucion = LOCALTIMESTAMP, resultado = left(p_motivo, 500)
    WHERE id = p_solicitudid AND estado = 'PENDIENTE';
    UPDATE autogestionsolicitudtoken SET usado = true, fechauso = LOCALTIMESTAMP WHERE solicitudid = p_solicitudid AND usado = false;
END;
$$;
