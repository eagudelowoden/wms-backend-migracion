/* =====================================================================
   AUTOGESTION (seriales + pallets + cajas + aprobacion por correo) - PostgreSQL
   Equivale a sql/autogestion_fase1.sql + sql/autogestion_aprobacion.sql (SQL Server).

   Ejecutar UNA VEZ POR ESQUEMA DE CLIENTE, cambiando la primera linea:
       SET search_path TO <esquema_del_cliente>, public;
   Es idempotente (se puede re-ejecutar).

   Diferencias respecto a SQL Server:
   - WmsWdGeneral.dbo.X  ->  general.x
   - THROW 500xx         ->  RAISE EXCEPTION 'mensaje' (el mensaje es el mismo)
   - Los SP son funciones. Las que devuelven filas devuelven columnas tipadas (integer, timestamp, varchar),
     por eso el backend no necesita CAST.
   - Los parametros con valor por defecto van al final (regla de PostgreSQL); el backend llama con
     notacion nombrada (p_nombre => valor).
   - "Validacion en seco" (ejecutar y hacer ROLLBACK): se hace con un bloque BEGIN..EXCEPTION, que en
     plpgsql es un subtransaccion; se lanza un error propio y se captura para deshacer los cambios.
   - Se toma el mismo candado por serial que usa el empaque (pg_advisory_xact_lock 'empaque:<id>'),
     para no mover un serial mientras se esta empacando.
   - cajaempaque.activo se asume boolean (como en el cliente 85).
   ===================================================================== */
