SET search_path TO general, public;

CREATE TABLE IF NOT EXISTS notificacioncorreo (
    id            integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_notificacioncorreo PRIMARY KEY,
    evento        varchar(60)   NOT NULL,
    clienteid     integer       NULL,
    para          text          NOT NULL,
    cc            text          NULL,
    activo        boolean       NOT NULL DEFAULT true,
    usuario       varchar(150)  NULL,
    fecha         timestamp(3)  NOT NULL DEFAULT LOCALTIMESTAMP,
    fechamodifica timestamp(3)  NULL
);

CREATE TABLE IF NOT EXISTS notificacioncorreoenvio (
    id            integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_notificacioncorreoenvio PRIMARY KEY,
    evento        varchar(80)   NOT NULL,
    clienteid     integer       NULL,
    referencia    varchar(100)  NULL,
    destinatarios text          NULL,
    asunto        varchar(300)  NULL,
    ok            boolean       NOT NULL DEFAULT false,
    error         varchar(1000) NULL,
    usuario       varchar(150)  NULL,
    fecha         timestamp(3)  NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_notificacioncorreoenvio_cliente ON notificacioncorreoenvio (clienteid, fecha DESC);

