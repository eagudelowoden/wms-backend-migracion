CREATE TABLE IF NOT EXISTS notificacionsonido (
    clienteid       integer      NOT NULL CONSTRAINT pk_notificacionsonido PRIMARY KEY,
    sonidoerror     varchar(30)  NOT NULL,
    sonidoduplicado varchar(30)  NOT NULL,
    sonidofallo     varchar(30)  NOT NULL,
    sonidook        varchar(30)  NOT NULL,
    repetir         boolean      NOT NULL DEFAULT true,
    usuario         varchar(150) NULL,
    fecha           timestamp(3) NOT NULL DEFAULT LOCALTIMESTAMP,
    volumen         integer      NULL,
    pulso           integer      NULL,
    pausa           integer      NULL
);
-- Si la tabla ya existia sin volumen / ritmo
ALTER TABLE notificacionsonido ADD COLUMN IF NOT EXISTS volumen integer;
ALTER TABLE notificacionsonido ADD COLUMN IF NOT EXISTS pulso integer;
ALTER TABLE notificacionsonido ADD COLUMN IF NOT EXISTS pausa integer;

CREATE TABLE IF NOT EXISTS documentoplantilla (
    id        integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_documentoplantilla PRIMARY KEY,
    clienteid integer      NOT NULL,
    tipo      varchar(40)  NOT NULL,
    config    text         NOT NULL,
    activo    boolean      NOT NULL DEFAULT true,
    usuario   varchar(150) NULL,
    fecha     timestamp(3) NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT ux_documentoplantilla UNIQUE (clienteid, tipo)
);

CREATE TABLE IF NOT EXISTS prealertacierre (
    id          integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_prealertacierre PRIMARY KEY,
    clienteid   integer      NOT NULL,
    prealertaid integer      NOT NULL,
    prealerta   varchar(50)  NULL,
    modo        varchar(10)  NOT NULL,
    esperados   integer      NULL,
    recibidos   integer      NULL,
    faltantes   integer      NULL,
    sobrantes   integer      NULL,
    novedades   integer      NULL,
    observacion varchar(500) NULL,
    usuario     varchar(150) NULL,
    fecha       timestamp(3) NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_prealertacierre_cliente ON prealertacierre (clienteid, prealertaid);

CREATE TABLE IF NOT EXISTS smartcardautomatica (
    clienteid integer      NOT NULL CONSTRAINT pk_smartcardautomatica PRIMARY KEY,
    codigosap varchar(50)  NOT NULL,
    destino   varchar(50)  NOT NULL DEFAULT 'SMARTCARD',
    usuario   varchar(150) NULL,
    fecha     timestamp(3) NOT NULL DEFAULT LOCALTIMESTAMP
);

