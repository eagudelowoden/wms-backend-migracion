SET search_path TO wmswdlegacycostarica, general, public;   -- <- ESQUEMA DEL CLIENTE (primero), luego general

-- Estructura por esquema ---------------------------------------------------------------
ALTER TABLE accesorio ADD COLUMN IF NOT EXISTS novedad varchar(50);
ALTER TABLE accesorio ADD COLUMN IF NOT EXISTS usuarioidmovimiento integer;
ALTER TABLE cosmetica ADD COLUMN IF NOT EXISTS usuarioasignadoid integer;

CREATE TABLE IF NOT EXISTS auditorianivelempaque (
    id            integer GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    empaqueid     integer NULL,
    serialid      integer NULL,
    nivelidanterior integer NULL,
    nivelidnuevo  integer NULL,
    usuarioid     integer NULL,
    fechacambio   timestamp(3) NULL DEFAULT LOCALTIMESTAMP
);

DO $$
DECLARE
    v_clienteid   integer := 85;     -- <- EDITAR: id del cliente en general.cliente
    v_modulodespacho integer;
    v_equiposok   boolean;
    v_accesoriosok boolean;
    v_despachado  integer;
    v_novedad     integer;
    v_novedadacc  integer;
    v_opcequipos  integer;
    v_opcaccesorios integer;
    v_wf          integer;
    v_tm          integer;
    v_n           integer;
    v_nombre      text;
BEGIN
    SELECT m.id INTO v_modulodespacho FROM general.modulo m WHERE m.nombre = 'Despacho' ORDER BY m.id LIMIT 1;
    IF v_modulodespacho IS NULL THEN
        RAISE EXCEPTION 'No existe el módulo Despacho en general.modulo.';
    END IF;

    -- 1. Catalogo Permiso (pestana y secciones de Despachado) --------------------------------------
    INSERT INTO general.permiso (moduloid, nombre, descripcion)
    SELECT v_modulodespacho, v.nombre, v.descripcion
    FROM (VALUES ('Opc_Despachado', 'Despacho'), ('Opc_Equipos', 'Despachado'), ('Opc_Accesorios', 'Despachado'))
         AS v(nombre, descripcion)
    WHERE NOT EXISTS (SELECT 1 FROM general.permiso p
                      WHERE p.moduloid = v_modulodespacho AND p.nombre = v.nombre AND p.descripcion = v.descripcion);

    -- 3b. Tipo de novedad de accesorios (ERROR CODIGO SAP, ERROR CANTIDAD, NO CONFORMIDAD) --------
    SELECT t.id INTO v_tm FROM tipomaestro t WHERE t.nombre = 'Tipo Novedad Accesorios' ORDER BY t.id LIMIT 1;
    IF v_tm IS NULL THEN
        INSERT INTO tipomaestro (nombre, descripcion, activo) VALUES ('Tipo Novedad Accesorios', 'Tipo Novedad Accesorios', true)
        RETURNING id INTO v_tm;
    END IF;
    INSERT INTO maestro (codigo, descripcion, tipomaestroid, activo, detalle, adicional)
    SELECT v.codigo, v.codigo, v_tm, true, '', 0
    FROM (VALUES ('ERROR CODIGO SAP'), ('ERROR CANTIDAD'), ('NO CONFORMIDAD')) AS v(codigo)
    WHERE NOT EXISTS (SELECT 1 FROM maestro m WHERE m.tipomaestroid = v_tm AND m.codigo = v.codigo);

    -- Perfiles ADMINISTRADOR del cliente, solo con lo que el esquema puede hacer
    v_equiposok := EXISTS (SELECT 1 FROM maestro m JOIN tipomaestro t ON t.id = m.tipomaestroid
                           WHERE UPPER(t.nombre) = 'TIPOLOGIAS' AND UPPER(m.codigo) = 'NO CONFORMIDAD' AND m.activo = true);
    v_accesoriosok := general.col_length('accesorio', 'novedad') IS NOT NULL
                      AND EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                                  WHERE n.nspname = current_schema() AND p.proname = 'pa_searchnoveltyaccesorypallet');

    INSERT INTO general.perfilpermiso (perfilid, permisoid)
    SELECT pf.id, pe.id
    FROM general.perfil pf
    CROSS JOIN general.permiso pe
    WHERE pf.clienteid = v_clienteid
      AND pf.nombre ILIKE '%ADMINISTRADOR%'
      AND pe.moduloid = v_modulodespacho
      AND ((pe.nombre = 'Opc_Despachado' AND pe.descripcion = 'Despacho' AND (v_equiposok OR v_accesoriosok))
        OR (pe.nombre = 'Opc_Equipos' AND pe.descripcion = 'Despachado' AND v_equiposok)
        OR (pe.nombre = 'Opc_Accesorios' AND pe.descripcion = 'Despachado' AND v_accesoriosok))
      AND NOT EXISTS (SELECT 1 FROM general.perfilpermiso x WHERE x.perfilid = pf.id AND x.permisoid = pe.id);
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RAISE NOTICE 'Permisos de Despachado asignados a perfiles ADMINISTRADOR: % (equipos %, accesorios %)',
        v_n, v_equiposok, v_accesoriosok;

    -- 2. Work flow de Despachado (destinos al guardar) --------------------------------------------
    SELECT e.id INTO v_despachado FROM general.estado e WHERE UPPER(e.nombre) = 'DESPACHADO' ORDER BY e.id LIMIT 1;
    SELECT e.id INTO v_novedad    FROM general.estado e WHERE UPPER(e.nombre) = 'NOVEDAD' ORDER BY e.id LIMIT 1;
    SELECT e.id INTO v_novedadacc FROM general.estado e WHERE UPPER(e.nombre) = 'NOVEDAD-ACCESORIOS' ORDER BY e.id LIMIT 1;
    SELECT p.id INTO v_opcequipos FROM general.permiso p
      WHERE p.moduloid = v_modulodespacho AND p.nombre = 'Opc_Equipos' AND p.descripcion = 'Despachado' LIMIT 1;
    SELECT p.id INTO v_opcaccesorios FROM general.permiso p
      WHERE p.moduloid = v_modulodespacho AND p.nombre = 'Opc_Accesorios' AND p.descripcion = 'Despachado' LIMIT 1;

    IF v_despachado IS NOT NULL THEN
        FOR v_n, v_wf IN SELECT * FROM (VALUES (v_opcequipos, v_novedad), (v_opcaccesorios, v_novedadacc)) AS x(opcion, destino)
        LOOP
            -- v_n = opcion, v_wf = destino (variables reutilizadas para el bucle)
            DECLARE v_id integer;
            BEGIN
                SELECT w.id INTO v_id FROM workflow w
                 WHERE w.moduloid = v_modulodespacho AND w.origenid = v_despachado AND w.opcionid = v_n AND w.tipologiaid = 0
                 LIMIT 1;
                IF v_id IS NULL THEN
                    INSERT INTO workflow (moduloid, origenid, opcionid, tipologiaid, nivelid)
                    VALUES (v_modulodespacho, v_despachado, v_n, 0, 0) RETURNING id INTO v_id;
                END IF;
                IF v_wf IS NOT NULL AND NOT EXISTS (SELECT 1 FROM workflowdestino d WHERE d.workflowid = v_id) THEN
                    INSERT INTO workflowdestino (workflowid, destinoid) VALUES (v_id, v_wf);
                END IF;
            END;
        END LOOP;
        RAISE NOTICE 'Work flow de Despachado listo';
    END IF;

    -- 3. Menus de Administracion (si el esquema tiene la tabla menu) -----------------------------
    IF to_regclass('menu') IS NOT NULL AND EXISTS (SELECT 1 FROM menu WHERE id = 'ADM') THEN
        INSERT INTO menu (id, descripcion, tipo, orden, accion, estado, icono, id_padre, view_name, controller_name)
        SELECT v.id, v.descripcion, 'item', v.orden, v.accion, 'activo', '', 'ADM', '', ''
        FROM (VALUES ('ADNOT', 'Notificaciones', 20, 'ADMNOT'),
                     ('ADDOC', 'Documentos', 21, 'ADMDOC'),
                     ('ADVAR', 'Variables de etiquetas', 22, 'ADMVAR')) AS v(id, descripcion, orden, accion)
        WHERE NOT EXISTS (SELECT 1 FROM menu m WHERE m.id = v.id);

        -- B1 (V2_6_2): menu de Autogestion, copia el de Cosmetica (PCOS) bajo Produccion
        INSERT INTO menu (id, descripcion, tipo, orden, accion, estado, icono, id_padre, view_name, controller_name)
        SELECT 'PAUT', 'Autogestión', tipo, (SELECT MAX(orden) + 1 FROM menu WHERE id_padre = 'PROD'),
               accion, estado, icono, id_padre, view_name, controller_name
        FROM menu
        WHERE id = 'PCOS' AND NOT EXISTS (SELECT 1 FROM menu WHERE id = 'PAUT');
    END IF;

    -- Modulos 44, 47, 48 (y 46 Autogestion) para los perfiles ADMINISTRADOR
    INSERT INTO general.perfilmodulo (perfilid, moduloid, orden)
    SELECT pf.id, mo.id, 0
    FROM general.perfil pf
    JOIN general.modulo mo ON mo.id IN (44, 46, 47, 48)
    WHERE pf.clienteid = v_clienteid AND pf.nombre ILIKE '%ADMINISTRADOR%'
      AND NOT EXISTS (SELECT 1 FROM general.perfilmodulo x WHERE x.perfilid = pf.id AND x.moduloid = mo.id);
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RAISE NOTICE 'Módulos 44/46/47/48 asignados a perfiles ADMINISTRADOR: %', v_n;

    -- 6e. Tipos de maestro de los parametros por cliente ---------------------------------------------
    FOREACH v_nombre IN ARRAY ARRAY['SmartCard Ingreso', 'Limpieza Caracteres', 'Diagnostico Serial3', 'Responsable Op', 'Tipo Empaque']
    LOOP
        IF NOT EXISTS (SELECT 1 FROM tipomaestro t WHERE t.nombre = v_nombre) THEN
            INSERT INTO tipomaestro (nombre, descripcion, activo) VALUES (v_nombre, v_nombre, true);
            RAISE NOTICE 'Tipo de maestro creado: %', v_nombre;
        END IF;
    END LOOP;

    -- Avisos
    IF NOT v_equiposok THEN
        RAISE NOTICE 'AVISO: falta la tipología NO CONFORMIDAD (Despachado no podrá regresar equipos)';
    END IF;
    IF NOT v_accesoriosok THEN
        RAISE NOTICE 'AVISO: falta la novedad de accesorios (cargar la parte 5 de funciones para este esquema)';
    END IF;
END $$;

