     - Work flow de Despachado: DESPACHADO -> NOVEDAD (equipos) y NOVEDAD-ACCESORIOS (accesorios).
     - Menus de Administracion ADNOT (modulo 44), ADDOC (47), ADVAR (48) y el menu PAUT de Autogestion (modulo 46).
     - Novedad de accesorios: columnas accesorio.novedad y usuarioidmovimiento, tipo de maestro y sus filas.
     - Tipos de maestro vacios: SmartCard Ingreso, Limpieza Caracteres, Diagnostico Serial3, Responsable Op, Tipo Empaque.
