CREATE TABLE IF NOT EXISTS codigosapregla (
    id          integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_codigosapregla PRIMARY KEY,
    clienteid   integer       NOT NULL,
    codigosapid integer       NOT NULL,
    campo       varchar(20)   NOT NULL,
    origen      varchar(20)   NOT NULL,
    operacion   varchar(20)   NOT NULL,
    parametro1  varchar(100)  NULL,
    parametro2  varchar(100)  NULL,
    momento     varchar(15)   NOT NULL DEFAULT 'INGRESO',
    activo      boolean       NOT NULL DEFAULT true,
    usuario     varchar(150)  NULL,
    fecha       timestamp(3)  NOT NULL DEFAULT LOCALTIMESTAMP
);
ALTER TABLE codigosapregla ADD COLUMN IF NOT EXISTS momento varchar(15) NOT NULL DEFAULT 'INGRESO';
CREATE UNIQUE INDEX IF NOT EXISTS ux_codigosapregla ON codigosapregla (clienteid, codigosapid, campo);

CREATE TABLE IF NOT EXISTS clienteconfig (
    clienteid integer       NOT NULL,
    clave     varchar(80)   NOT NULL,
    valor     text          NULL,
    usuario   varchar(150)  NULL,
    fecha     timestamp(3)  NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_clienteconfig PRIMARY KEY (clienteid, clave)
);

CREATE TABLE IF NOT EXISTS basealmacen (
    id        integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_basealmacen PRIMARY KEY,
    clienteid integer       NOT NULL,
    serial    varchar(100)  NOT NULL,
    codigosap varchar(100)  NULL,
    estadosap varchar(100)  NULL,
    estadorr  varchar(100)  NULL,
    lote      varchar(100)  NULL,
    fecha     timestamp(3)  NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_basealmacen_serial ON basealmacen (clienteid, serial);

CREATE TABLE IF NOT EXISTS variableetiqueta (
    id          integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_variableetiqueta PRIMARY KEY,
    clienteid   integer       NOT NULL,
    nombre      varchar(50)   NOT NULL,
    descripcion varchar(200)  NULL,
    aplica      varchar(20)   NOT NULL,
    origen      varchar(20)   NOT NULL,
    operacion   varchar(20)   NOT NULL,
    parametro1  varchar(100)  NULL,
    parametro2  varchar(100)  NULL,
    consulta    text          NULL,
    activo      boolean       NOT NULL DEFAULT true,
    usuario     varchar(150)  NULL,
    fecha       timestamp(3)  NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_variableetiqueta ON variableetiqueta (clienteid, nombre);

