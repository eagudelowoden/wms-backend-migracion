CREATE TABLE IF NOT EXISTS boletaconsecutivo (
    clienteid integer NOT NULL,
    anio      integer NOT NULL,
    ultimo    integer NOT NULL,
    CONSTRAINT pk_boletaconsecutivo PRIMARY KEY (clienteid, anio)
);

CREATE TABLE IF NOT EXISTS boletamovimiento (
    id                integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_boletamovimiento PRIMARY KEY,
    clienteid         integer       NOT NULL,
    documento         varchar(20)   NOT NULL,
    anio              integer       NULL,
    consecutivo       integer       NULL,
    fechaentrega      date          NULL,
    origen            varchar(100)  NULL,
    destino           varchar(100)  NULL,
    observaciones     varchar(1000) NULL,
    estado            varchar(20)   NOT NULL DEFAULT 'RESERVADA',
    usuarioid         integer       NULL,
    usuarionombre     varchar(150)  NULL,
    fecha             timestamp(3)  NOT NULL DEFAULT LOCALTIMESTAMP,
    usuariodespachoid integer       NULL,
    fechadespacho     timestamp(3)  NULL,
    usuariocancelaid  integer       NULL,
    fechacancela      timestamp(3)  NULL
);
CREATE INDEX IF NOT EXISTS ix_boletamovimiento_cliente ON boletamovimiento (clienteid, estado, fecha DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ux_boletamovimiento_consecutivo ON boletamovimiento (clienteid, anio, consecutivo)
    WHERE consecutivo IS NOT NULL;

CREATE TABLE IF NOT EXISTS boletamovimientopallet (
    id          integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_boletamovimientopallet PRIMARY KEY,
    boletaid    integer       NOT NULL CONSTRAINT fk_boletamovimientopallet_boleta REFERENCES boletamovimiento (id),
    clienteid   integer       NOT NULL,
    palletid    integer       NOT NULL,
    nopallet    varchar(50)   NULL,
    codigosap   varchar(50)   NULL,
    descripcion varchar(200)  NULL,
    cantidad    integer       NULL,
    tipologia   varchar(100)  NULL,
    activo      boolean       NOT NULL DEFAULT true,
    despachado  boolean       NOT NULL DEFAULT false,
    -- sql/2026-10-29_boleta_forecast_largos.sql: conteos por tipo para la boleta
    equipos     integer       NULL,
    accesorios  integer       NULL,
    smartcards  integer       NULL
);
CREATE INDEX IF NOT EXISTS ix_boletamovimientopallet_boleta ON boletamovimientopallet (boletaid);
CREATE UNIQUE INDEX IF NOT EXISTS ux_boletamovimientopallet_activo ON boletamovimientopallet (clienteid, palletid)
    WHERE activo = true;

-- Respaldo de Despachado -> Novedades
CREATE TABLE IF NOT EXISTS despachoreversa (
    id             integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_despachoreversa PRIMARY KEY,
    clienteid      integer        NOT NULL,
    db             varchar(128)   NOT NULL,
    serial         varchar(100)   NOT NULL,
    serialid       integer        NOT NULL,
    despachoid     integer        NOT NULL,
    pedidosap      varchar(50)    NULL,
    fechadespacho  timestamp(3)   NULL,
    palletdespacho varchar(50)    NULL,
    motivo         varchar(300)   NOT NULL,
    despachojson   text           NULL,
    empaquejson    text           NULL,
    usuarioid      integer        NULL,
    usuarionombre  varchar(150)   NULL,
    fecha          timestamp(3)   NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_despachoreversa_cliente ON despachoreversa (clienteid, serial);

CREATE TABLE IF NOT EXISTS despachoreversaacc (
    id             integer GENERATED BY DEFAULT AS IDENTITY NOT NULL CONSTRAINT pk_despachoreversaacc PRIMARY KEY,
    clienteid      integer        NOT NULL,
    db             varchar(128)   NOT NULL,
    pedidosap      varchar(50)    NOT NULL,
    codigosap      varchar(50)    NULL,
    modelo         varchar(200)   NULL,
    tipoaccesorio  varchar(50)    NULL,
    estadolimpieza varchar(50)    NULL,
    cantidad       integer        NOT NULL,
    accesorioids   text           NULL,
    motivo         varchar(300)   NOT NULL,
    despachojson   text           NULL,
    palletnovedad  varchar(50)    NULL,
    usuarioid      integer        NULL,
    usuarionombre  varchar(150)   NULL,
    fecha          timestamp(3)   NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_despachoreversaacc_cliente ON despachoreversaacc (clienteid, pedidosap);
