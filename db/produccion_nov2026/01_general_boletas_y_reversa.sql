SET search_path TO general, public;

-- Funcion auxiliar usada por el backend en lugar de COL_LENGTH de SQL Server:
-- devuelve 1 si la columna existe, NULL si no. La tabla se resuelve con el search_path (esquema del cliente) o calificada.
CREATE OR REPLACE FUNCTION general.col_length(p_tabla text, p_columna text)
RETURNS integer LANGUAGE sql STABLE AS $$
    SELECT 1 FROM pg_attribute a
    WHERE a.attrelid = to_regclass(p_tabla) AND a.attname = lower(p_columna) AND a.attnum > 0 AND NOT a.attisdropped
$$;

